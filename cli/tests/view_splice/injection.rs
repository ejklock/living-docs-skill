#[test]
fn injection_through_an_input_glob_is_refused_naming_the_glob() {
    let bundle = repository("injection-glob", true);
    for glob in ["x -->\r# INJECTED HEADING", "a,b", "a|b", "a b", "a-->b"] {
        let args = ["--inputs", glob, "--command", "x"];
        let named = format!("glob `{glob}`");
        refused(&bundle, "view/crates", &args, GRAPH, &[&named]);
    }
}

#[test]
fn a_flowchart_with_arrows_comments_subgraphs_and_inline_markup_is_accepted() {
    let bundle = repository("accepted-flowchart", true);
    let chart = "flowchart TD\n  %% a comment\n  subgraph one [\"Group <br> name\"]\n    a[\"x<br>y\"] --> b\n  end\n  b -->|label| c\n";
    stamped(&bundle, chart, &["--command", COMMAND]);
    let text = view_text(&bundle);
    assert_eq!(text.matches("```").count(), 2, "{text}");
    assert!(text.contains("a[\"x<br>y\"] --> b"), "{text}");
    assert_eq!(stale_views(&bundle), (Some(0), 0));
}

#[test]
fn injection_through_a_command_that_ends_the_comment_is_refused() {
    let bundle = repository("injection-command", true);
    for command in ["x --!> <h1>INJECTED HEADING</h1>", "x --> <h1>H</h1>"] {
        let args = ["--inputs", "Cargo.toml", "--command", command];
        refused(&bundle, "view/crates", &args, GRAPH, &["command"]);
    }
}

