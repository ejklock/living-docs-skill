//! Mermaid text that holds a fence or a marker line is refused whole: the
//! splice never writes a byte outside the generated region.

use super::*;

const CLOSE_AND_INJECT: &str =
    "graph TD\n a-->b\n```\n<!-- end generated -->\nINJECTED outside\n~~~\n";

fn existing_region(bundle: &Path) {
    stamped(bundle, GRAPH, &["--command", COMMAND]);
}

#[test]
fn injection_that_closes_the_region_and_opens_a_tilde_fence_is_refused() {
    let bundle = repository("injection-close", true);
    existing_region(&bundle);
    refused(
        &bundle,
        "view/crates",
        &["--inputs", "Cargo.toml"],
        CLOSE_AND_INJECT,
        &["line 3"],
    );
}

#[test]
fn injection_is_refused_when_the_region_sits_in_the_middle_of_the_body() {
    let bundle = repository("injection-middle", true);
    existing_region(&bundle);
    let text = view_text(&bundle);
    write(
        &bundle,
        VIEW,
        &format!("{text}\n## After\n\nProse after.\n"),
    );
    refused(
        &bundle,
        "view/crates",
        &["--inputs", "Cargo.toml"],
        CLOSE_AND_INJECT,
        &["line 3"],
    );
}

