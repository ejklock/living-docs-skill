//! `manage view <view> --splice`: Mermaid text from standard input becomes the
//! view's stamped generated region.
mod common;
#[path = "view_splice/injection.rs"]
mod injection;
use common::{living_docs, write, Scratch};
use fs_store::FsStore;
use living_docs_core::inputs_hash::inputs_hash;
use serde_json::Value;
use std::path::{Path, PathBuf};
use std::process::{Output, Stdio};
use std::{collections::BTreeMap, fs, io::Write};

const VIEW: &str = "architecture/crates.md";
const GRAPH: &str = "graph TD\n a-->b\n";
const COMMAND: &str = "cargo metadata | jq";

const ROOT_INDEX: &str = "# Index\n\n- [architecture](architecture/index.md)\n";
const VIEW_TEXT: &str = "---\ntype: Architecture View\ntitle: Crates\ndescription: The crates.\nkind: component\ntimestamp: 2026-11-20T10:00:00Z\n---\n\n# Crates\n\nProse before.\n\n## Drift instrument\n\nDrift caught by: the stamp.\n";

/// A scratch repository: an indexed bundle at `docs` and a `Cargo.toml`.
fn repository(label: &str, with_git: bool) -> Scratch {
    let bundle = common::temp_bundle("view-splice", label);
    let root = bundle.parent().unwrap();
    if with_git {
        fs::create_dir_all(root.join(".git")).unwrap();
    }
    fs::write(root.join("Cargo.toml"), "[workspace]\n").unwrap();
    write(&bundle, "index.md", ROOT_INDEX);
    write(&bundle, VIEW, VIEW_TEXT);
    common::index_bundle(&bundle);
    bundle
}

fn splice(bundle: &Path, view: &str, args: &[&str], stdin: &str) -> Output {
    let docs = bundle.to_str().unwrap();
    let mut child = living_docs()
        .args(["--docs-dir", docs, "manage", "view", view])
        .args(["--splice", "--plain"])
        .args(args)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap();
    let mut pipe = child.stdin.take().unwrap();
    pipe.write_all(stdin.as_bytes()).unwrap();
    drop(pipe);
    child.wait_with_output().unwrap()
}

fn stamp(bundle: &Path, stdin: &str, extra: &[&str]) -> Output {
    let mut args = vec!["--inputs", "Cargo.toml"];
    args.extend_from_slice(extra);
    splice(bundle, "view/crates", &args, stdin)
}

/// A splice of `Cargo.toml` that must succeed.
fn stamped(bundle: &Path, stdin: &str, extra: &[&str]) {
    let output = stamp(bundle, stdin, extra);
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
}

fn stderr(output: &Output) -> String {
    String::from_utf8_lossy(&output.stderr).into_owned()
}

fn view_text(bundle: &Path) -> String {
    fs::read_to_string(bundle.join(VIEW)).unwrap()
}

fn hash_of(root: &Path, globs: &[&str]) -> String {
    let globs: Vec<String> = globs.iter().map(|glob| (*glob).to_owned()).collect();
    inputs_hash(&FsStore::rooted(root), &globs).unwrap()
}

fn tree(bundle: &Path) -> BTreeMap<PathBuf, Vec<u8>> {
    let mut found = BTreeMap::new();
    let mut pending = vec![bundle.parent().unwrap().to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in fs::read_dir(dir).unwrap().map(Result::unwrap) {
            let path = entry.path();
            if path.is_dir() {
                pending.push(path);
            } else {
                found.insert(path.clone(), fs::read(path).unwrap());
            }
        }
    }
    found
}

fn stale_views(bundle: &Path) -> (Option<i32>, usize) {
    let mut command = living_docs();
    let output = command.args(["check", "--json", "--"]).arg(bundle);
    let output = output.output().unwrap();
    let json: Value = serde_json::from_slice(&output.stdout).unwrap();
    let advisories = json["advisories"].as_array().into_iter().flatten();
    let stale = advisories.filter(|a| a["kind"] == "stale-view");
    (output.status.code(), stale.count())
}

fn opening_of(text: &str) -> &str {
    let is_opening = |line: &&str| line.starts_with("<!-- generated by:");
    text.lines().find(is_opening).unwrap()
}

/// Runs a splice that must be refused: exit 2, a message holding every
/// fragment, and no byte of the repository changed.
fn refused(bundle: &Path, view: &str, args: &[&str], stdin: &str, fragments: &[&str]) {
    let before = tree(bundle);
    let output = splice(bundle, view, args, stdin);
    let message = stderr(&output);
    assert_eq!(output.status.code(), Some(2), "{message}");
    for fragment in fragments {
        assert!(message.contains(fragment), "{fragment:?} not in {message}");
    }
    assert_eq!(tree(bundle), before);
}

#[test]
fn splice_writes_one_stamped_region_that_check_finds_fresh() {
    let bundle = repository("writes", true);
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    let hash = hash_of(bundle.parent().unwrap(), &["Cargo.toml"]);
    let opening = format!("<!-- generated by: {COMMAND} | inputs: Cargo.toml | sha256: {hash} -->");
    let fence = "```mermaid\ngraph TD\n a-->b\n```";
    let region = format!("\n{opening}\n{fence}\n<!-- end generated -->\n");
    let text = view_text(&bundle);
    assert!(text.ends_with(&format!("the stamp.\n{region}")), "{text}");
    assert_eq!(text.matches("<!-- generated by:").count(), 1);
    assert_eq!(stale_views(&bundle), (Some(0), 0));
}

#[test]
fn splicing_the_same_input_twice_writes_no_byte() {
    let bundle = repository("idempotent", true);
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    let before = tree(&bundle);
    let modified = || fs::metadata(bundle.join(VIEW)).unwrap().modified().unwrap();
    let stamped_at = modified();
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    assert_eq!(tree(&bundle), before);
    assert_eq!(modified(), stamped_at);
}

#[test]
fn a_changed_input_makes_check_report_stale_view_until_the_next_splice() {
    let bundle = repository("stale", true);
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    let manifest = bundle.parent().unwrap().join("Cargo.toml");
    fs::write(manifest, "[workspace]\n# x\n").unwrap();
    assert_eq!(stale_views(&bundle), (Some(0), 1));
    stamped(&bundle, GRAPH, &[]);
    assert_eq!(stale_views(&bundle), (Some(0), 0));
}

#[test]
fn replacing_without_a_command_keeps_the_existing_one_and_an_explicit_one_replaces_it() {
    let bundle = repository("command", true);
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    stamped(&bundle, "graph TD\n c-->d\n", &[]);
    let text = view_text(&bundle);
    assert!(
        opening_of(&text).contains(&format!("generated by: {COMMAND} |")),
        "{text}"
    );
    assert!(text.contains("c-->d") && !text.contains("a-->b"), "{text}");
    stamped(&bundle, GRAPH, &["--command", "other"]);
    assert!(opening_of(&view_text(&bundle)).contains("generated by: other |"));
}

#[test]
fn replacing_keeps_every_byte_outside_the_region() {
    let bundle = repository("outside", true);
    stamped(&bundle, GRAPH, &["--command", COMMAND]);
    let edited = view_text(&bundle).replace("Prose before.", "Prose before, edited.");
    write(&bundle, VIEW, &edited);
    stamped(&bundle, "graph TD\n c-->d\n", &[]);
    let (outside, _) = edited.split_once("\n<!-- generated").unwrap();
    assert!(
        view_text(&bundle).starts_with(outside),
        "{}",
        view_text(&bundle)
    );
}

#[test]
fn input_that_is_already_fenced_is_not_fenced_again() {
    let bundle = repository("fenced", true);
    stamped(
        &bundle,
        "\n```mermaid\ngraph TD\n a-->b\n```\n\n",
        &["--command", COMMAND],
    );
    let text = view_text(&bundle);
    assert_eq!(text.matches("```mermaid").count(), 1, "{text}");
    assert_eq!(text.matches("```").count(), 2, "{text}");
}

const REQUIRED: [&str; 4] = ["--inputs", "Cargo.toml", "--command", "x"];

#[test]
fn refuses_a_non_view_reference_and_a_missing_view() {
    let bundle = repository("not-a-view", true);
    assert!(common::run_new(&bundle, "adr", "First").status.success());
    let said = ["not an architecture view"];
    refused(&bundle, "adr/0001", &REQUIRED, GRAPH, &said);
    let said = ["no record found for view/nope"];
    refused(&bundle, "view/nope", &REQUIRED, GRAPH, &said);
}

#[test]
fn refuses_empty_standard_input_and_a_new_region_without_a_command() {
    let bundle = repository("empty", true);
    refused(&bundle, "view/crates", &REQUIRED, "\n  \n", &["empty"]);
    let no_command = ["--inputs", "Cargo.toml"];
    refused(&bundle, "view/crates", &no_command, GRAPH, &["--command"]);
}

#[test]
fn refuses_a_view_with_two_generated_regions() {
    let bundle = repository("two-regions", true);
    let region = "<!-- generated by: x -->\n```mermaid\ngraph TD\n```\n<!-- end generated -->\n";
    write(&bundle, VIEW, &format!("{VIEW_TEXT}\n{region}\n{region}"));
    let said = ["several generated regions; splice supports one"];
    refused(&bundle, "view/crates", &REQUIRED, GRAPH, &said);
}

#[test]
fn refuses_an_input_glob_that_leaves_the_repository_or_is_unsupported() {
    let bundle = repository("bad-glob", true);
    for glob in ["/abs", "../x", "a{b,c}"] {
        let args = ["--inputs", glob, "--command", "x"];
        refused(&bundle, "view/crates", &args, GRAPH, &[glob]);
    }
}

#[test]
fn refuses_inputs_in_a_bundle_with_no_git_repository() {
    let bundle = repository("no-git", false);
    let said = ["--inputs need a git repository"];
    refused(&bundle, "view/crates", &REQUIRED, GRAPH, &said);
}

#[test]
fn refuses_a_glob_whose_every_match_is_gitignored() {
    let bundle = repository("ignored", true);
    let root = bundle.parent().unwrap();
    fs::write(root.join(".gitignore"), "gen/\n").unwrap();
    fs::create_dir_all(root.join("gen")).unwrap();
    fs::write(root.join("gen/schema.toml"), "a = 1\n").unwrap();
    let args = ["--inputs", "gen/schema.toml", "--command", "x"];
    let said = ["gen/schema.toml", ".gitignore"];
    refused(&bundle, "view/crates", &args, GRAPH, &said);
}

#[test]
fn a_glob_matching_nothing_writes_the_region_and_warns_naming_it() {
    let bundle = repository("nothing", true);
    let args = ["--inputs", "none/*.toml", "--command", "x"];
    let output = splice(&bundle, "view/crates", &args, GRAPH);
    assert_eq!(output.status.code(), Some(0), "{}", stderr(&output));
    assert!(
        stderr(&output).contains("none/*.toml"),
        "{}",
        stderr(&output)
    );
    let empty = hash_of(bundle.parent().unwrap(), &["none/*.toml"]);
    assert!(opening_of(&view_text(&bundle)).contains(&empty));
}

fn splice_over_mcp(bundle: &Path, inputs: &str) -> Value {
    let mut session = common::mcp_session::Session::start(bundle);
    session.initialize();
    let arguments = serde_json::json!({"operation": "view", "view": "view/crates",
        "inputs": [inputs], "command": COMMAND, "mermaid": GRAPH});
    let call = serde_json::json!({"name": "manage", "arguments": arguments});
    session.request(2, "tools/call", &call)["result"].clone()
}

#[test]
fn the_manage_tool_splices_the_same_bytes_as_the_command() {
    let (by_tool, by_command) = (repository("tool", true), repository("command-line", true));
    let result = splice_over_mcp(&by_tool, "Cargo.toml");
    assert_ne!(result["isError"], true, "{result}");
    assert_eq!(result["structuredContent"]["created"], true, "{result}");
    stamped(&by_command, GRAPH, &["--command", COMMAND]);
    assert_eq!(view_text(&by_tool), view_text(&by_command));
}

#[test]
fn the_manage_tool_returns_a_refusal_as_an_error_result_and_changes_no_byte() {
    let bundle = repository("tool-refuses", true);
    let before = tree(&bundle);
    let result = splice_over_mcp(&bundle, "/abs");
    assert_eq!(result["isError"], true, "{result}");
    assert!(result.to_string().contains("/abs"), "{result}");
    assert_eq!(tree(&bundle), before);
}
