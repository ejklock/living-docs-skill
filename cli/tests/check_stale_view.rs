//! The `stale-view` advisory: an architecture view whose stamped generated
//! region records a hash that differs from the current hash of its input
//! globs. It never fails the gate and is skipped outside a repository.

use fs_store::FsStore;
use living_docs_core::inputs_hash::inputs_hash;
use serde_json::Value;
use std::fs;
use std::path::Path;

mod common;
use common::{living_docs, write};

const VIEW: &str = "architecture/crates.md";

fn view(opening: &str, outside: &str) -> String {
    format!(
        "---\ntype: Architecture View\ntitle: Crates\ndescription: The crates.\nkind: component\ntimestamp: 2026-11-20T10:00:00Z\n---\n\n# Crates\n\n{outside}\n\n{opening}\n```mermaid\nflowchart LR\n    A --> B\n```\n<!-- end generated -->\n\n## Drift instrument\n\nDrift caught by: the stamp.\n"
    )
}

fn stamped(hash: &str) -> String {
    format!("<!-- generated by: cargo metadata | inputs: Cargo.toml | sha256: {hash} -->")
}

/// A scratch repository holding a bundle at `docs` with the view `contents`
/// and a `Cargo.toml`, indexed.
fn repository(label: &str, contents: &str, with_git: bool) -> common::Scratch {
    let bundle = common::temp_bundle("stale-view", label);
    let root = bundle.parent().unwrap().to_path_buf();
    if with_git {
        fs::create_dir_all(root.join(".git")).unwrap();
    }
    fs::write(root.join("Cargo.toml"), "[workspace]\n").unwrap();
    write(
        &bundle,
        "index.md",
        "# Index\n\n- [architecture](architecture/index.md)\n",
    );
    write(&bundle, VIEW, contents);
    common::index_bundle(&bundle);
    bundle
}

fn current_hash(bundle: &Path) -> String {
    let root = bundle.parent().unwrap();
    inputs_hash(&FsStore::rooted(root), &["Cargo.toml".to_owned()]).unwrap()
}

fn check_json(bundle: &Path) -> (Option<i32>, Vec<(String, String)>) {
    let output = living_docs()
        .args(["check", "--json", "--"])
        .arg(bundle)
        .output()
        .expect("failed to run living-docs check");
    let json: Value = serde_json::from_slice(&output.stdout).expect("check --json prints JSON");
    let found = json["advisories"]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|a| a["kind"] == "stale-view")
        .map(|a| {
            (
                a["file"].as_str().unwrap().to_owned(),
                a["message"].as_str().unwrap().to_owned(),
            )
        })
        .collect();
    (output.status.code(), found)
}

fn fresh(label: &str) -> common::Scratch {
    let bundle = repository(label, &view("<!-- generated by: x -->", "Prose."), true);
    let opening = stamped(&current_hash(&bundle));
    write(&bundle, VIEW, &view(&opening, "Prose."));
    bundle
}

#[test]
fn a_view_stamped_with_the_current_hash_raises_nothing() {
    let bundle = fresh("current");
    assert_eq!(check_json(&bundle), (Some(0), vec![]));
}

#[test]
fn a_changed_input_raises_one_advisory_naming_the_view_and_the_glob() {
    let bundle = fresh("changed");
    let manifest = bundle.parent().unwrap().join("Cargo.toml");
    fs::write(manifest, "[workspace]\n# x\n").unwrap();
    let (code, found) = check_json(&bundle);
    assert_eq!(code, Some(0));
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].0.ends_with(VIEW), "{found:?}");
    assert!(found[0].1.contains("Cargo.toml"), "{found:?}");
}

#[test]
fn editing_the_prose_outside_the_region_raises_nothing() {
    let bundle = fresh("prose");
    let opening = stamped(&current_hash(&bundle));
    write(&bundle, VIEW, &view(&opening, "Other prose, edited."));
    assert_eq!(check_json(&bundle), (Some(0), vec![]));
}

#[test]
fn a_legacy_unstamped_region_raises_nothing() {
    let bundle = repository("legacy", &view("<!-- generated by: x -->", "Prose."), true);
    assert_eq!(check_json(&bundle), (Some(0), vec![]));
}

#[test]
fn a_malformed_stamp_raises_an_advisory_saying_it_cannot_be_checked() {
    let bundle = repository(
        "malformed",
        &view(&stamped(&"a".repeat(63)), "Prose."),
        true,
    );
    let (code, found) = check_json(&bundle);
    assert_eq!(code, Some(0));
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].1.contains("cannot be checked"), "{found:?}");
}

#[test]
fn a_bundle_in_no_repository_raises_nothing() {
    let stale = stamped(&"0".repeat(64));
    let bundle = repository("no-repository", &view(&stale, "Prose."), false);
    assert_eq!(check_json(&bundle), (Some(0), vec![]));
}
