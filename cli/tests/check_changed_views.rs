//! `check --changed-inputs-from` keeps a stamped view's `stale-view` advisory
//! in scope when a listed path matches one of the view's input globs, and only
//! that: it never brings a record's violation into scope. The distributed
//! pre-commit hook in changed-only mode feeds it every staged path on stdin,
//! stays silent when `check` finds nothing, and never blocks on an advisory.

use fs_store::FsStore;
use living_docs_core::inputs_hash::inputs_hash;
use serde_json::Value;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

mod common;
use common::{living_docs, write};

const VIEW: &str = "architecture/crates.md";
const GLOB: &str = "src/**/*.rs";

fn view(opening: &str) -> String {
    format!(
        "---\ntype: Architecture View\ntitle: Crates\ndescription: The crates.\nkind: component\ntimestamp: 2026-11-20T10:00:00Z\n---\n\n# Crates\n\nProse.\n\n{opening}\n```mermaid\nflowchart LR\n    A --> B\n```\n<!-- end generated -->\n\n## Drift instrument\n\nDrift caught by: the stamp.\n"
    )
}

/// A command seeing only the scratch repository: no inherited environment and
/// no system or user configuration, with the test binary's directory first on
/// `PATH` so a hook resolves it.
fn isolated(program: &str, repo: &Path, vars: &[(&str, &str)]) -> Command {
    let binary = PathBuf::from(env!("CARGO_BIN_EXE_living-docs"));
    let bin_dir = binary.parent().expect("the test binary has a directory");
    let mut command = Command::new(program);
    command
        .current_dir(repo)
        .env_clear()
        .env("HOME", repo)
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("PATH", format!("{}:/usr/bin:/bin", bin_dir.display()))
        .env("GIT_AUTHOR_NAME", "T")
        .env("GIT_AUTHOR_EMAIL", "t@example.com")
        .env("GIT_COMMITTER_NAME", "T")
        .env("GIT_COMMITTER_EMAIL", "t@example.com")
        .envs(vars.iter().copied());
    command
}

fn git(repo: &Path, args: &[&str]) -> Output {
    isolated("git", repo, &[])
        .args(args)
        .output()
        .expect("failed to run git")
}

/// A repository holding a bundle at `docs`, a view stamped fresh over `glob`,
/// source and unrelated files, and a legacy violation in `docs/index.md`, all
/// committed without the hook.
fn repository_over(label: &str, glob: &str) -> common::Scratch {
    let bundle = common::temp_bundle("check-changed-views", label);
    let root = bundle.parent().unwrap().to_path_buf();
    git(&root, &["init", "-q"]);
    write(&root, "src/a.rs", "fn a() {}\n");
    write(&root, "src/my dir/b c.rs", "fn b() {}\n");
    write(&root, "Cargo.toml", "[workspace]\n");
    write(&root, "crates/x/Cargo.toml", "[package]\n");
    write(&root, "README.md", "readme\n");
    write(
        &bundle,
        "index.md",
        "# Index\n\n- [architecture](architecture/index.md)\n",
    );
    write(&bundle, VIEW, &view("<!-- generated by: x -->"));
    common::index_bundle(&bundle);
    let hash = inputs_hash(&FsStore::rooted(&root), &[glob.to_owned()]).unwrap();
    let opening = format!("<!-- generated by: ls | inputs: {glob} | sha256: {hash} -->");
    write(&bundle, VIEW, &view(&opening));
    write(
        &bundle,
        "index.md",
        "# Index\n\n- [architecture](architecture/index.md)\n- [gone](missing.md)\n",
    );
    git(&root, &["add", "-A"]);
    let commit = git(&root, &["commit", "-q", "--no-verify", "-m", "base"]);
    assert!(commit.status.success(), "{commit:?}");
    bundle
}

fn repository(label: &str) -> common::Scratch {
    repository_over(label, GLOB)
}

fn root_of(bundle: &Path) -> &Path {
    bundle.parent().unwrap()
}

/// `check --json` from the repository root over `docs` with `args`, feeding
/// `stdin`; the exit code and the raw report.
fn check_json(bundle: &Path, args: &[&str], stdin: &[u8]) -> (Option<i32>, Vec<u8>) {
    let mut child = living_docs()
        .current_dir(root_of(bundle))
        .args(["check", "--json"])
        .args(args)
        .args(["--", "docs"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .expect("failed to run living-docs check");
    child.stdin.take().unwrap().write_all(stdin).unwrap();
    let output = child.wait_with_output().unwrap();
    (output.status.code(), output.stdout)
}

fn finding_files(report: &[u8], section: &str, kind: &str) -> Vec<String> {
    let json: Value = serde_json::from_slice(report).expect("check --json prints JSON");
    json[section]
        .as_array()
        .into_iter()
        .flatten()
        .filter(|f| kind.is_empty() || f["kind"] == kind)
        .map(|f| f["file"].as_str().unwrap().to_owned())
        .collect()
}

fn stale_views_for(bundle: &Path, inputs: &[u8]) -> Vec<String> {
    let (code, report) = check_json(bundle, &["--changed-inputs-from", "-"], inputs);
    assert_eq!(code, Some(0));
    finding_files(&report, "advisories", "stale-view")
}

#[test]
fn a_listed_input_brings_its_stale_view_into_scope() {
    let bundle = repository("input");
    write(root_of(&bundle), "src/a.rs", "fn a() { 1; }\n");
    let found = stale_views_for(&bundle, b"src/a.rs\0");
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].ends_with(VIEW), "{found:?}");
}

#[test]
fn a_listed_input_never_brings_a_records_violation_into_scope() {
    let bundle = repository("no-violation");
    let (code, report) = check_json(&bundle, &["--changed-inputs-from", "-"], b"index.md\0");
    assert_eq!(code, Some(0));
    assert_eq!(
        finding_files(&report, "violations", ""),
        Vec::<String>::new()
    );
}

#[test]
fn a_nested_path_does_not_match_a_glob_naming_a_root_file() {
    let bundle = repository_over("nested", "Cargo.toml");
    write(root_of(&bundle), "Cargo.toml", "[workspace]\n# x\n");
    assert_eq!(
        stale_views_for(&bundle, b"crates/x/Cargo.toml\0"),
        Vec::<String>::new()
    );
    assert_eq!(stale_views_for(&bundle, b"Cargo.toml\0").len(), 1);
}

#[test]
fn a_listed_path_matching_no_glob_leaves_the_report_as_without_it() {
    let bundle = repository("no-glob");
    write(root_of(&bundle), "src/a.rs", "fn a() { 1; }\n");
    let scoped = ["--changed-files=docs/index.md"];
    let without = check_json(&bundle, &scoped, b"");
    let with = check_json(
        &bundle,
        &[
            "--changed-files=docs/index.md",
            "--changed-inputs-from",
            "-",
        ],
        b"README.md\0",
    );
    assert_eq!(with.0, without.0);
    assert_eq!(
        String::from_utf8_lossy(&with.1),
        String::from_utf8_lossy(&without.1)
    );
}

#[test]
fn names_with_a_space_or_a_newline_match_their_glob() {
    let bundle = repository("odd-names");
    write(root_of(&bundle), "src/a.rs", "fn a() { 1; }\n");
    for name in ["src/my dir/b c.rs", "src/odd\nname.rs", "src/-dash.rs"] {
        let found = stale_views_for(&bundle, format!("{name}\0").as_bytes());
        assert_eq!(found.len(), 1, "{name:?}: {found:?}");
    }
    let none = stale_views_for(&bundle, b"other\nname.txt\0");
    assert_eq!(none, Vec::<String>::new());
}

/// Runs the distributed hook, read by `bash` so the file is never executed,
/// over what is staged, in changed-only mode.
fn run_hook(bundle: &Path) -> Output {
    let hook = Path::new(env!("CARGO_MANIFEST_DIR")).join("../skills/living-docs/hooks/pre-commit");
    isolated(
        "bash",
        root_of(bundle),
        &[("LIVING_DOCS_CHECK_CHANGED_ONLY", "1")],
    )
    .arg(hook)
    .output()
    .expect("failed to run the hook")
}

#[test]
fn staging_the_deletion_of_an_input_shows_stale_view() {
    let bundle = repository("hook-delete");
    let root = root_of(&bundle);
    git(root, &["rm", "-q", "src/a.rs"]);
    let out = run_hook(&bundle);
    assert_eq!(out.status.code(), Some(0), "{}", hook_text(&out));
    assert!(hook_text(&out).to_lowercase().contains("stale-view"));
}

#[test]
fn staging_the_rename_of_an_input_shows_stale_view() {
    let bundle = repository("hook-rename");
    let root = root_of(&bundle);
    fs::create_dir_all(root.join("lib")).unwrap();
    git(root, &["mv", "src/a.rs", "lib/a.rs"]);
    let out = run_hook(&bundle);
    assert_eq!(out.status.code(), Some(0), "{}", hook_text(&out));
    assert!(hook_text(&out).to_lowercase().contains("stale-view"));
}

fn hook_text(out: &Output) -> String {
    format!(
        "{}{}",
        String::from_utf8_lossy(&out.stdout),
        String::from_utf8_lossy(&out.stderr)
    )
}

#[test]
fn staging_only_an_input_shows_stale_view_and_passes() {
    let bundle = repository("hook-input");
    let root = root_of(&bundle);
    write(root, "src/a.rs", "fn a() { 1; }\n");
    git(root, &["add", "src/a.rs"]);
    let out = run_hook(&bundle);
    assert_eq!(out.status.code(), Some(0), "{}", hook_text(&out));
    assert!(hook_text(&out).to_lowercase().contains("stale-view"));
}

#[test]
fn staging_only_an_unrelated_file_leaves_the_hook_silent() {
    let bundle = repository("hook-unrelated");
    let root = root_of(&bundle);
    write(root, "src/a.rs", "fn a() { 1; }\n");
    write(root, "README.md", "edited\n");
    git(root, &["add", "README.md"]);
    let out = run_hook(&bundle);
    assert_eq!(out.status.code(), Some(0));
    assert_eq!(hook_text(&out), "");
}

#[test]
fn staging_an_index_outside_the_bundle_passes_over_legacy_debt() {
    for outside in ["index.md", "packages/a/docs/index.md"] {
        let bundle = repository("hook-outside");
        let root = root_of(&bundle);
        write(root, outside, "# Outside\n");
        git(root, &["add", outside]);
        let out = run_hook(&bundle);
        assert_eq!(out.status.code(), Some(0), "{outside}: {}", hook_text(&out));
        assert_eq!(hook_text(&out), "", "{outside}");
    }
}

#[test]
fn staging_a_great_many_outside_files_overflows_no_argument_list() {
    let bundle = repository("hook-many");
    let root = root_of(&bundle);
    let padding = "p".repeat(150);
    for n in 0..20_000 {
        write(root, &format!("vendor/{n:05}-{padding}.txt"), "x\n");
    }
    git(root, &["add", "vendor"]);
    let out = run_hook(&bundle);
    assert_eq!(out.status.code(), Some(0), "{}", hook_text(&out));
    assert_eq!(hook_text(&out), "");
}
