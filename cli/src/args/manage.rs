//! The `manage` verb's operations: the bundle's index and canonical form,
//! the install and uninstall of skills and hooks, and shell completions.

use super::help;
use super::sub::{InstallCmd, UninstallCmd};
use clap::Subcommand;
use clap_complete::Shell;
use std::path::PathBuf;

#[derive(Subcommand)]
pub(crate) enum ManageCmd {
    /// With no `doc_type`, regenerates every registered type's index.
    #[command(about = help::INDEX_ABOUT, long_about = None, after_help = help::with_exit_codes(help::INDEX_EXAMPLES))]
    Index {
        #[arg(value_name = "TYPE", help = help::doc_type_help())]
        doc_type: Option<String>,
    },
    #[command(about = help::FMT_ABOUT, long_about = None, after_help = help::with_exit_codes(help::FMT_EXAMPLES))]
    Fmt {
        /// A bundle root or a single record path; filesystem backend only.
        paths: Vec<PathBuf>,
        /// Report what is pending without writing anything; exits 1 when a
        /// record is not canonical.
        #[arg(long)]
        check: bool,
    },
    #[command(about = help::HTML_ABOUT, long_about = None, after_help = help::with_exit_codes(help::HTML_EXAMPLES))]
    Html {
        /// Where to write the page; default .living-docs/html/index.html
        /// under the current directory. Parent directories are created.
        #[arg(long, value_name = "PATH")]
        out: Option<PathBuf>,
        /// The mermaid.js file to inline; without it the installed copy is
        /// used, else the pinned CDN script tag.
        #[arg(long, value_name = "PATH")]
        mermaid: Option<PathBuf>,
    },
    #[command(about = help::VIEW_ABOUT, long_about = None, after_help = help::with_exit_codes(help::VIEW_EXAMPLES))]
    View {
        /// The architecture view: `view/<slug>`, `architecture/<slug>` or its path.
        view: String,
        /// Write the Mermaid text read from standard input into the view's
        /// generated region and stamp it.
        #[arg(long, required = true)]
        splice: bool,
        /// The globs, from the repository root, whose files the region is
        /// generated from; their hash goes into the stamp.
        #[arg(long, num_args = 1.., required = true, value_name = "GLOB")]
        inputs: Vec<String>,
        /// The command that regenerates the text, recorded in the marker and
        /// never run; required when the view has no region yet.
        #[arg(long, value_name = "TEXT")]
        command: Option<String>,
    },
    #[command(about = help::INSTALL_ABOUT, long_about = None, after_help = help::with_exit_codes(help::INSTALL_EXAMPLES))]
    Install {
        #[command(subcommand)]
        action: InstallCmd,
    },
    /// There is no `uninstall skills`: no verb wrote a skills-directory
    /// pointer to undo.
    #[command(about = help::UNINSTALL_ABOUT, long_about = None, after_help = help::with_exit_codes(help::UNINSTALL_EXAMPLES))]
    Uninstall {
        #[command(subcommand)]
        action: UninstallCmd,
    },
    /// Generated by `clap_complete` straight from this command tree, so it
    /// never drifts from the verbs and flags above.
    #[command(about = help::COMPLETIONS_ABOUT, long_about = None, after_help = help::with_exit_codes(help::COMPLETIONS_EXAMPLES))]
    Completions {
        /// The shell to generate the completion script for.
        shell: Shell,
    },
}
