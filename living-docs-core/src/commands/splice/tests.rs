use super::*;
use crate::generated_region::{parse_regions, render_opening, Region};
use crate::inputs_hash::inputs_hash;
use crate::test_support::WritableMapStore;

const VIEW: &str = "/b/architecture/crates.md";
const FRONT: &str = "---\ntype: Architecture View\ntitle: Crates\ndescription: The crates.\nkind: component\ntimestamp: 2026-11-20T10:00:00Z\n---\n";
const COMMAND: &str = "cargo metadata | jq";
const GRAPH: &str = "graph TD\n a-->b\n";

fn store(body: &str) -> WritableMapStore {
    WritableMapStore::seeded(&[(VIEW, &format!("{FRONT}{body}"))]).with_repository(
        &[("Cargo.toml", "[workspace]\n")],
        &[("gen/schema.toml", "a = 1\n")],
    )
}

fn inputs(globs: &[&str]) -> Vec<String> {
    globs.iter().map(|glob| (*glob).to_owned()).collect()
}

fn splice(
    store: &WritableMapStore,
    globs: &[&str],
    command: Option<&str>,
) -> Result<Spliced, String> {
    let request = Request {
        view: "view/crates",
        inputs: &inputs(globs),
        command,
        mermaid: GRAPH,
    };
    apply(store, Path::new("/b"), &request)
}

fn opening(store: &WritableMapStore, command: &str, globs: &[&str]) -> String {
    let hash = inputs_hash(store, &inputs(globs)).unwrap();
    render_opening(command, &inputs(globs), &hash)
}

fn region_text(opening: &str) -> String {
    format!("{opening}\n```mermaid\ngraph TD\n a-->b\n```\n<!-- end generated -->\n")
}

#[test]
fn a_rendered_opening_parses_back_to_its_command_globs_and_hash() {
    let hash = "ab".repeat(32);
    let several = inputs(&["a/*.toml", "b/**", "c?.json"]);
    for globs in [inputs(&["Cargo.toml"]), several] {
        let line = render_opening(COMMAND, &globs, &hash);
        let text = format!("{line}\n```mermaid\nx\n```\n<!-- end generated -->\n");
        let expected = Region {
            command: COMMAND.to_owned(),
            inputs: globs,
            hash: Some(hash.clone()),
            span: 2..5,
        };
        assert_eq!(parse_regions(&text), Ok(vec![expected]));
    }
}

#[test]
fn a_view_with_no_region_gets_one_after_the_body_and_one_blank_line() {
    let store = store("\n# Crates\n\nProse.\n");
    let done = splice(&store, &["Cargo.toml"], Some(COMMAND)).unwrap();
    let region = region_text(&opening(&store, COMMAND, &["Cargo.toml"]));
    let expected = format!("{FRONT}\n# Crates\n\nProse.\n\n{region}");
    assert_eq!(store.contents(VIEW), expected);
    assert!(done.created && done.warnings.is_empty());
}

#[test]
fn replacing_a_region_keeps_every_byte_outside_it() {
    let old = region_text("<!-- generated by: old -->").replace("a-->b", "x-->y");
    let store = store(&format!("\n# Crates\n\nBefore.\n\n{old}\nAfter.\n"));
    let done = splice(&store, &["Cargo.toml"], None);
    assert_eq!(done.as_ref().map(|d| d.created), Ok(false), "{done:?}");
    let region = region_text(&opening(&store, "old", &["Cargo.toml"]));
    let expected = format!("{FRONT}\n# Crates\n\nBefore.\n\n{region}\nAfter.\n");
    assert_eq!(store.contents(VIEW), expected);
}

#[test]
fn a_glob_matching_only_ignored_paths_is_refused_by_name_and_writes_nothing() {
    let store = store("\n# Crates\n");
    let before = store.contents(VIEW);
    let error = splice(&store, &["gen/schema.toml"], Some(COMMAND)).unwrap_err();
    assert!(
        error.contains("gen/schema.toml") && error.contains(".gitignore"),
        "{error}"
    );
    assert_eq!(store.contents(VIEW), before);
}

#[test]
fn a_glob_matching_nothing_is_written_with_a_warning_naming_it() {
    let store = store("\n# Crates\n");
    let done = splice(&store, &["none/*.toml"], Some(COMMAND)).unwrap();
    assert_eq!(done.warnings.len(), 1);
    assert!(
        done.warnings[0].contains("none/*.toml"),
        "{:?}",
        done.warnings
    );
    assert!(store.contents(VIEW).contains("<!-- generated by:"));
}

#[test]
fn a_command_that_cannot_sit_in_a_marker_is_refused() {
    let store = store("\n# Crates\n");
    for command in ["two\nlines", "ends --> early", "a | inputs: b"] {
        let error = splice(&store, &["Cargo.toml"], Some(command)).unwrap_err();
        assert!(error.contains("command"), "{command:?}: {error}");
    }
    assert!(!store.contents(VIEW).contains("generated by"));
}

#[test]
fn a_store_with_no_repository_refuses_the_inputs() {
    let store = WritableMapStore::seeded(&[(VIEW, &format!("{FRONT}\n# Crates\n"))]);
    let error = splice(&store, &["Cargo.toml"], Some(COMMAND)).unwrap_err();
    assert!(error.contains("--inputs need a git repository"), "{error}");
}

#[test]
fn mermaid_text_with_a_fence_or_a_marker_line_is_refused_naming_the_line() {
    let cases = [
        ("graph TD\n```\nx\n", "line 2"),
        ("graph TD\n~~~\nx\n", "line 2"),
        ("graph TD\n  ```js\nx\n", "line 2"),
        ("graph TD\n<!-- end generated -->\n", "line 2"),
        ("a\nb\n<!-- generated by: evil -->\n", "line 3"),
        ("```mermaid\ngraph TD\n```\n```\n", "line 3"),
        (
            "```mermaid\ngraph TD\n```\n<!-- end generated -->\n",
            "line 1",
        ),
    ];
    for (text, line) in cases {
        let error = fenced(text).unwrap_err();
        assert!(error.contains(line), "{text:?}: {error}");
    }
}

#[test]
fn mermaid_text_with_its_own_single_fence_pair_or_none_is_accepted() {
    assert_eq!(
        fenced("graph TD\n a-->b\n").unwrap(),
        "```mermaid\ngraph TD\n a-->b\n```"
    );
    let own = "\n```mermaid\ngraph TD\n```\n\n";
    assert_eq!(fenced(own).unwrap(), "```mermaid\ngraph TD\n```");
}

#[test]
fn a_rendered_region_must_be_exactly_one_region_from_its_first_to_its_last_line() {
    let globs = inputs(&["Cargo.toml"]);
    let hash = "ab".repeat(32);
    let open = render_opening(COMMAND, &globs, &hash);
    let whole = format!("{open}\n```mermaid\nx\n```\n<!-- end generated -->");
    assert!(ensure_whole_region(&whole, COMMAND, &globs).is_ok());
    let escaped = [
        format!("{whole}\nINJECTED outside"),
        format!("{open}\n```mermaid\nx\n```\n<!-- end generated -->\nout\n~~~\n```\n<!-- end generated -->"),
        format!("lead\n{whole}"),
        format!("{whole}\n{whole}"),
        format!("{open}\n```mermaid\nx\n```"),
    ];
    for region in escaped {
        assert!(
            ensure_whole_region(&region, COMMAND, &globs).is_err(),
            "{region}"
        );
    }
}

#[test]
fn mermaid_text_with_a_control_character_or_a_loose_fence_is_refused_naming_the_line() {
    let cases = [
        ("graph TD\r a-->b\r```\r", "line 1"),
        ("graph TD\n a\rb\n", "line 2"),
        ("graph TD\0\n", "line 1"),
        ("graph TD\n a\u{2028}b\n", "line 2"),
        ("graph TD\n a\u{7}b\n", "line 2"),
        ("```mermaid`\ngraph TD\n```\n", "line 1"),
        ("```mermaid js\ngraph TD\n```\n", "line 1"),
        ("```mermaid\ngraph TD\n", "line 1"),
        ("graph TD\n```\n", "line 2"),
        ("graph TD\n \t<b>x\n", "line 2"),
        ("graph TD\n\t`x\n", "line 2"),
        ("graph TD\n  ~x\n", "line 2"),
    ];
    for (text, line) in cases {
        let error = fenced(text).unwrap_err();
        assert!(error.contains(line), "{text:?}: {error}");
    }
}

#[test]
fn a_flowchart_with_arrows_comments_subgraphs_and_inline_markup_is_accepted() {
    let chart = "flowchart TD\n  %% note\n  subgraph one [\"G <br> n\"]\n    a[\"x<br>y\"] --> b\n  end\n  b -->|l| c\n\ttab --> indented\n";
    assert_eq!(fenced(chart).unwrap(), format!("```mermaid\n{chart}```"));
}

#[test]
fn a_command_with_a_control_character_or_a_marker_sequence_is_refused() {
    let store = store("\n# Crates\n");
    let commands = [
        "a\tb",
        "a\u{0}b",
        "a\u{2028}b",
        "x <!-- y",
        "x --!> <h1>H</h1>",
        "a | sha256: b",
        "a | inputs: b",
    ];
    for command in commands {
        let error = splice(&store, &["Cargo.toml"], Some(command)).unwrap_err();
        assert!(error.contains("command"), "{command:?}: {error}");
    }
}

#[test]
fn a_glob_outside_the_allowed_characters_is_refused_naming_it() {
    let store = store("\n# Crates\n");
    let before = store.contents(VIEW);
    for glob in ["x -->\r# H", "a,b", "a|b", "a b", "a-->b", "a\tb", "é.toml"] {
        let error = splice(&store, &[glob], Some(COMMAND)).unwrap_err();
        assert!(
            error.contains(&format!("glob `{glob}`")),
            "{glob:?}: {error}"
        );
    }
    assert_eq!(store.contents(VIEW), before);
}

#[test]
fn a_glob_made_of_path_characters_wildcards_and_package_marks_is_accepted() {
    let store = store("\n# Crates\n");
    let globs = [
        "**/Cargo.toml",
        "@scope/pkg/*.json",
        "a-b_c.d/?.x",
        "c++/x~1.toml",
    ];
    assert!(splice(&store, &globs, Some(COMMAND)).is_ok());
}

#[test]
fn mermaid_text_that_is_only_its_own_fences_is_refused_as_empty() {
    for text in ["```mermaid\n```\n", "```mermaid\n\n  \n```\n"] {
        let error = fenced(text).unwrap_err();
        assert!(error.contains("empty"), "{text:?}: {error}");
    }
}
