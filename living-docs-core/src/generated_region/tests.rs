use super::*;

const HASH: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

fn stamped(command: &str, hash: &str) -> String {
    format!("<!-- generated by: {command} | inputs: Cargo.toml, */Cargo.toml | sha256: {hash} -->")
}

fn error_of(body: &str) -> RegionError {
    parse_regions(body).unwrap_err()
}

#[test]
fn a_stamped_region_yields_command_globs_hash_and_span() {
    let body = format!(
        "# View\n\n{}\n```mermaid\ngraph TD\n```\n<!-- end generated -->\n",
        stamped("cargo metadata", HASH)
    );
    let regions = parse_regions(&body).unwrap();
    assert_eq!(
        regions,
        vec![Region {
            command: "cargo metadata".to_string(),
            inputs: vec!["Cargo.toml".to_string(), "*/Cargo.toml".to_string()],
            hash: Some(HASH.to_string()),
            span: 4..7,
        }]
    );
}

#[test]
fn a_legacy_opening_line_yields_an_unstamped_region() {
    let body = "<!-- generated by: make graph -->\nbody\n<!-- end generated -->\n";
    let regions = parse_regions(body).unwrap();
    assert_eq!(regions.len(), 1);
    assert_eq!(regions[0].command, "make graph");
    assert!(regions[0].inputs.is_empty());
    assert_eq!(regions[0].hash, None);
    assert_eq!(regions[0].span, 2..3);
}

#[test]
fn a_legacy_command_holding_a_pipe_stays_whole() {
    let body = "<!-- generated by: cargo metadata | jq . -->\n<!-- end generated -->\n";
    let regions = parse_regions(body).unwrap();
    assert_eq!(regions[0].command, "cargo metadata | jq .");
    assert_eq!(regions[0].span, 2..2);
}

#[test]
fn two_regions_in_one_body_both_parse() {
    let body = format!(
        "{}\na\n<!-- end generated -->\ntext\n<!-- generated by: b -->\nc\n<!-- end generated -->\n",
        stamped("a", HASH)
    );
    let regions = parse_regions(&body).unwrap();
    assert_eq!(regions.len(), 2);
    assert_eq!(regions[0].command, "a");
    assert_eq!(regions[1].command, "b");
    assert_eq!(regions[1].span, 6..7);
}

#[test]
fn a_marker_inside_a_fenced_block_is_ignored() {
    let body = "```md\n<!-- generated by: x -->\n```\n~~~\n<!-- end generated -->\n~~~\n";
    assert_eq!(parse_regions(body).unwrap(), vec![]);
}

#[test]
fn inputs_without_a_hash_name_the_line() {
    let body = "text\n<!-- generated by: a | inputs: x -->\n<!-- end generated -->\n";
    let error = error_of(body);
    assert_eq!(error.line, 2);
    assert!(error.message.contains("sha256"), "{error}");
}

#[test]
fn a_hash_without_inputs_names_the_line() {
    let body = format!("<!-- generated by: a | sha256: {HASH} -->\n<!-- end generated -->\n");
    let error = error_of(&body);
    assert_eq!(error.line, 1);
    assert!(error.message.contains("inputs"), "{error}");
}

#[test]
fn a_63_character_hash_is_an_error() {
    let body = format!("\n{}\n<!-- end generated -->\n", stamped("a", &HASH[..63]));
    let error = error_of(&body);
    assert_eq!(error.line, 2);
    assert!(error.message.contains("64"), "{error}");
}

#[test]
fn an_uppercase_hash_is_an_error() {
    let body = format!(
        "{}\n<!-- end generated -->\n",
        stamped("a", &HASH.to_uppercase())
    );
    assert_eq!(error_of(&body).line, 1);
}

#[test]
fn an_opening_without_a_closing_names_the_opening_line() {
    let body = "a\nb\n<!-- generated by: x -->\nbody\n";
    let error = error_of(body);
    assert_eq!(error.line, 3);
    assert_eq!(
        error.to_string(),
        "line 3: opening marker with no closing end-generated marker"
    );
}

#[test]
fn an_opening_inside_an_open_region_names_the_first_opening() {
    let body = "<!-- generated by: x -->\n<!-- generated by: y -->\n<!-- end generated -->\n";
    assert_eq!(error_of(body).line, 1);
}

#[test]
fn a_closing_without_an_opening_names_the_line() {
    let error = error_of("a\n\n<!-- end generated -->\n");
    assert_eq!(error.line, 3);
    assert_eq!(error.to_string(), "line 3: closing marker with no opening");
}

#[test]
fn a_doubled_inputs_key_names_the_line() {
    let body = format!("\n<!-- generated by: a | inputs: x | inputs: y | sha256: {HASH} -->\n<!-- end generated -->\n");
    let error = error_of(&body);
    assert_eq!(error.line, 2);
    assert!(error.message.contains("twice"), "{error}");
}

#[test]
fn a_doubled_sha256_key_names_the_line() {
    let body = format!("<!-- generated by: a | inputs: x | sha256: {HASH} | sha256: {HASH} -->\n<!-- end generated -->\n");
    let error = error_of(&body);
    assert_eq!(error.line, 1);
    assert!(error.message.contains("twice"), "{error}");
}
