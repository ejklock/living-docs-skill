//! Every body of up to five lines drawn from an opening marker, the closing
//! marker, two fence openers, plain text and an empty line parses without
//! panicking. When it parses, each region's span is well formed, the regions
//! are ordered and do not overlap, and with no fence in the body every
//! opening and every closing marker belongs to exactly one region.

use super::{parse_regions, CLOSING};
use crate::exhaustive::for_each_sequence;

const OPENING_LINE: &str = "<!-- generated by: build -->";
const LINES: [&str; 6] = [OPENING_LINE, CLOSING, "```", "~~~", "x", ""];

#[test]
fn parsing_never_panics_and_yields_ordered_spans_for_every_short_body() {
    let cases = for_each_sequence(&LINES, 5, &mut |lines| {
        let body = lines.join("\n");
        let Ok(regions) = parse_regions(&body) else {
            return;
        };
        for region in &regions {
            assert!(region.span.start <= region.span.end, "{body:?}");
            assert!(region.span.end <= lines.len(), "{body:?}");
            assert_eq!(lines[region.span.end - 1], CLOSING, "{body:?}");
            assert_eq!(lines[region.span.start - 2], OPENING_LINE, "{body:?}");
        }
        for pair in regions.windows(2) {
            assert!(pair[0].span.end < pair[1].span.start, "{body:?}");
        }
        if !lines
            .iter()
            .any(|line| line.starts_with("```") || line.starts_with("~~~"))
        {
            let openings = lines.iter().filter(|line| **line == OPENING_LINE).count();
            let closings = lines.iter().filter(|line| **line == CLOSING).count();
            assert_eq!(regions.len(), openings, "{body:?}");
            assert_eq!(regions.len(), closings, "{body:?}");
        }
    });
    assert_eq!(cases, 1 + 6 + 36 + 216 + 1296 + 7776);
}
