use super::*;
use crate::store::RepositoryFiles;
use crate::test_support::MapStore;
use std::cell::Cell;
use std::io;
use std::path::{Path, PathBuf};

/// A store that counts how often the repository files are asked for.
struct Counting {
    inner: MapStore,
    asked: Cell<usize>,
}

impl DocStore for Counting {
    fn list(&self, root: &Path) -> io::Result<Vec<PathBuf>> {
        self.inner.list(root)
    }
    fn read(&self, path: &Path) -> io::Result<String> {
        self.inner.read(path)
    }
    fn write(&self, path: &Path, contents: &str) -> io::Result<()> {
        self.inner.write(path, contents)
    }
    fn rename(&self, from: &Path, to: &Path) -> io::Result<()> {
        self.inner.rename(from, to)
    }
    fn repository_files(&self, globs: &[String]) -> Option<RepositoryFiles> {
        self.asked.set(self.asked.get() + 1);
        self.inner.repository_files(globs)
    }
}

fn view(opening: &str) -> String {
    format!(
        "---\ntype: Architecture View\ntitle: V\n---\n\n# V\n\n{opening}\nbody\n<!-- end generated -->\n"
    )
}

fn stamp(globs: &str, hash: &str) -> String {
    format!("<!-- generated by: cmd | inputs: {globs} | sha256: {hash} -->")
}

fn current(globs: &str) -> String {
    let (store, _) = MapStore::seeded(&[("Cargo.toml", "a")]);
    inputs_hash(&store, &[globs.to_owned()]).unwrap()
}

fn run(views: &[(&str, String)]) -> (Vec<(String, String)>, usize) {
    let mut seed: Vec<(&str, &str)> = vec![("Cargo.toml", "a")];
    seed.extend(views.iter().map(|(path, text)| (*path, text.as_str())));
    let (inner, all_md) = MapStore::seeded(&seed);
    let all_md: Vec<PathBuf> = all_md
        .into_iter()
        .filter(|path| path.extension().is_some_and(|ext| ext == "md"))
        .collect();
    let store = Counting {
        inner,
        asked: Cell::new(0),
    };
    let mut reporter = Reporter::new();
    check_stale_view(&store, &all_md, &mut reporter);
    let found = reporter
        .advisories
        .into_iter()
        .inspect(|advisory| assert_eq!(advisory.kind, kinds::STALE_VIEW))
        .map(|advisory| (advisory.file, advisory.message))
        .collect();
    (found, store.asked.get())
}

#[test]
fn an_equal_hash_is_silent() {
    let opening = stamp("Cargo.toml", &current("Cargo.toml"));
    assert!(run(&[("architecture/a.md", view(&opening))]).0.is_empty());
}

#[test]
fn a_different_hash_is_one_advisory_with_the_opening_line_and_the_globs() {
    let opening = stamp("Cargo.toml", &"0".repeat(64));
    let (found, _) = run(&[("architecture/a.md", view(&opening))]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert_eq!(found[0].0, "architecture/a.md");
    assert!(found[0].1.contains("line 8"), "{found:?}");
    assert!(found[0].1.contains("Cargo.toml"), "{found:?}");
}

#[test]
fn two_views_with_one_glob_set_hash_it_once() {
    let opening = stamp("Cargo.toml", &"0".repeat(64));
    let (found, asked) = run(&[
        ("architecture/a.md", view(&opening)),
        ("architecture/b.md", view(&opening)),
    ]);
    assert_eq!(found.len(), 2);
    assert_eq!(asked, 1);
}

#[test]
fn an_invalid_glob_is_an_advisory_saying_it_cannot_be_checked() {
    let opening = stamp("{a,b}", &"0".repeat(64));
    let (found, _) = run(&[("architecture/a.md", view(&opening))]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].1.contains("cannot be checked"), "{found:?}");
}

#[test]
fn a_record_outside_the_architecture_directory_is_not_judged() {
    let opening = stamp("Cargo.toml", &"0".repeat(64));
    assert!(run(&[("domain/a.md", view(&opening))]).0.is_empty());
}

#[test]
fn only_the_stale_region_of_two_is_advised_at_its_own_line() {
    let fresh = stamp("Cargo.toml", &current("Cargo.toml"));
    let stale = stamp("Cargo.toml, Cargo.toml", &"0".repeat(64));
    let text = format!("{}\n{stale}\nbody\n<!-- end generated -->\n", view(&fresh));
    let (found, _) = run(&[("architecture/a.md", text)]);
    assert_eq!(found.len(), 1, "{found:?}");
    assert!(found[0].1.contains("line 12"), "{found:?}");
}

#[test]
fn a_retired_view_is_still_judged() {
    let opening = stamp("Cargo.toml", &"0".repeat(64));
    let text = view(&opening).replacen("title: V", "title: V\nstatus: Superseded", 1);
    assert_eq!(run(&[("architecture/a.md", text)]).0.len(), 1);
}
